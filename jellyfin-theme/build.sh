#!/usr/bin/env bash
# Build dist/theme.css from the vendored ElegantFin, the vendored fonts and our own src/ files.
#   build.sh           write dist/theme.css
#   build.sh --check   rebuild into a temp file, fail if dist/theme.css is out of date, then lint it
# Works from any directory: paths are resolved from this script's folder.
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
dist="$here/dist/theme.css"
export LC_ALL=C # fixed glob order on every machine

die() { printf 'build.sh: %s\n' "$*" >&2; exit 1; }

mode=build
case "${1:-}" in
  "") ;;
  --check) mode=check ;;
  -h|--help) sed -n '2,5p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
  *) die "unknown option '$1' (use --check or no option)" ;;
esac

# Concatenate everything into $1, in a fixed order.
build_into() {
  local out="$1" f
  local -a vendor fonts src
  shopt -s nullglob
  vendor=("$here"/vendor/elegantfin/*.css)
  fonts=("$here"/vendor/fonts/*.css)
  src=("$here"/src/*.css)
  shopt -u nullglob

  [ "${#src[@]}" -gt 0 ] || die "no CSS files in src/"
  if [ "${#vendor[@]}" -eq 0 ]; then
    printf 'build.sh: warning: vendor/elegantfin/ has no CSS yet, building with src/ only (vendor ElegantFin first, see README)\n' >&2
  fi

  {
    printf '/*\n'
    printf ' * h1n054ur theme for Jellyfin. GENERATED by jellyfin-theme/build.sh, do not edit.\n'
    printf ' * Edit jellyfin-theme/src/ and run build.sh again.\n'
    if [ -s "$here/vendor/VERSIONS" ]; then
      printf ' *\n * Vendored sources (vendor/VERSIONS):\n'
      # Drop blank and comment lines, and anything that could close this comment.
      grep -v -e '^[[:space:]]*$' -e '^[[:space:]]*#' "$here/vendor/VERSIONS" | sed -e 's#\*/#* /#g' -e 's/^/ *   /'
    else
      printf ' *\n * Vendored sources: none pinned yet (vendor/VERSIONS missing).\n'
    fi
    printf ' */\n'
    for f in "${vendor[@]}" "${fonts[@]}" "${src[@]}"; do
      printf '\n/* ---- %s ---- */\n' "${f#"$here"/}"
      cat "$f"
      # Make sure every file ends with a newline before the next one starts.
      [ -z "$(tail -c1 "$f")" ] || printf '\n'
    done
  } > "$out"
}

# Light structural lint without installing anything: braces balance (outside comments and
# strings), no unclosed comment or string, and no @import or url() pointing outside
# (the theme must not load anything from the internet). Comments are ignored.
lint() {
  local file="$1" rc=0
  awk '
    BEGIN {
      depth = 0; incomment = 0; instr = ""; errors = 0
      q = "\x27"
      remote_import = "@import[^;]*(https?:)?//"
      remote_url = "url\\([ \t]*[\"" q "]?(https?:)?//"
    }
    {
      line = $0
      code = ""
      n = length(line)
      for (i = 1; i <= n; i++) {
        c = substr(line, i, 1); nx = substr(line, i + 1, 1)
        if (incomment) { if (c == "*" && nx == "/") { incomment = 0; i++ } continue }
        code = code c
        if (instr != "") {
          if (c == "\\") { i++; continue }
          if (c == instr) instr = ""
          continue
        }
        if (c == "/" && nx == "*") { incomment = 1; cstart = NR; i++; code = substr(code, 1, length(code) - 1); continue }
        if (c == "\"" || c == "\x27") { instr = c; sstart = NR; continue }
        if (c == "{") depth++
        else if (c == "}") {
          depth--
          if (depth < 0) { printf "line %d: unexpected }\n", NR; errors++; depth = 0 }
        }
      }
      if (instr != "") { printf "line %d: unclosed string (CSS strings cannot span lines)\n", sstart; errors++; instr = "" }
      lc = tolower(code)
      if (lc ~ remote_import || lc ~ remote_url) {
        printf "line %d: loads something from outside, vendor it instead: %s\n", NR, code; errors++
      }
    }
    END {
      if (incomment) { printf "line %d: unclosed comment\n", cstart; errors++ }
      if (depth > 0) { printf "end of file: %d unclosed {\n", depth; errors++ }
      exit errors > 0
    }
  ' "$file" || rc=1

  return "$rc"
}

mkdir -p "$here/dist"

if [ "$mode" = build ]; then
  tmp="$(mktemp "$here/dist/.theme.XXXXXX")"
  trap 'rm -f "$tmp"' EXIT
  build_into "$tmp"
  if ! lint_out="$(lint "$tmp")"; then
    printf '%s\n' "$lint_out" >&2
    die "lint failed, dist/theme.css not written"
  fi
  mv "$tmp" "$dist"
  trap - EXIT
  printf 'wrote %s (%s bytes)\n' "${dist#"$PWD"/}" "$(wc -c < "$dist")"
  exit 0
fi

# --check
tmp="$(mktemp)"
trap 'rm -f "$tmp"' EXIT
build_into "$tmp"
[ -f "$dist" ] || die "dist/theme.css is missing, run jellyfin-theme/build.sh"
if ! cmp -s "$tmp" "$dist"; then
  diff -u "$dist" "$tmp" | head -n 40 >&2 || true
  die "dist/theme.css is out of date, run jellyfin-theme/build.sh and commit the result"
fi
if ! lint_out="$(lint "$dist")"; then
  printf '%s\n' "$lint_out" >&2
  die "lint failed on dist/theme.css"
fi
printf 'jellyfin-theme: dist/theme.css is current and passes lint\n'
